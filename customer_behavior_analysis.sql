select * from customer limit 20


--Q1. What is the total revenue generated by male vs. female customers?
select gender, sum("purchase_amount") as revenue
from customer
group by gender;

--Q2. Which customers used a discount but still spent more than the average purchase amount? 
SELECT customer_id, purchase_amount
FROM customer 
WHERE discount_applied = 'Yes' 
  AND purchase_amount >= (SELECT AVG(purchase_amount) FROM customer);

--Q3. Which are the top 5 products with the highest average review rating?
SELECT "item_purchased", AVG("review_rating") AS "Average Product Rating"
FROM customer
GROUP BY "item_purchased"
ORDER BY "Average Product Rating" DESC
LIMIT 5;






-- Q4. Compare the average Purchase Amounts between Standard and Express Shipping.
SELECT 
    "shipping_type", 
    ROUND(AVG("purchase_amount"::numeric), 2) AS avg_purchase_amount
FROM customer
WHERE "shipping_type" IN ('Standard','Express')
GROUP BY "shipping_type";


-- Q5. Do subscribed customers spend more? Compare average spend and total revenue between subscribers and non-subscribers.
SELECT 
    "subscription_status",
    ROUND(AVG("purchase_amount"::numeric), 2) AS avg_spend,
    SUM("purchase_amount") AS total_revenue
FROM customer
GROUP BY "subscription_status";


-- Q6. Which 5 products have the highest percentage of purchases with discounts applied?
SELECT 
    "item_purchased",
    ROUND(100.0 * COUNT(CASE WHEN "discount_applied" = 'Yes' THEN 1 END) / COUNT(*), 2) AS discount_percentage
FROM customer
GROUP BY "item_purchased"
ORDER BY discount_percentage DESC
LIMIT 5;


-- Q7. Segment customers into New, Returning, and Loyal based on their total number of previous purchases, and show the count of each segment.
SELECT 
    CASE 
        WHEN "previous_purchases" = 0 THEN 'New'
        WHEN "previous_purchases" BETWEEN 1 AND 10 THEN 'Returning'
        ELSE 'Loyal'
    END AS customer_segment,
    COUNT(*) AS total_customers
FROM customer
GROUP BY customer_segment
ORDER BY total_customers DESC;


-- Q8. What are the top 3 most purchased products within each category?
WITH ranked_products AS (
    SELECT 
        "category",
        "item_purchased",
        COUNT(*) AS total_orders,
        DENSE_RANK() OVER(PARTITION BY "category" ORDER BY COUNT(*) DESC) AS rank
    FROM customer
    GROUP BY "category", "item_purchased"
)
SELECT 
    "category",
    "item_purchased",
    total_orders
FROM ranked_products
WHERE rank <= 3;


-- Q9. Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe?
SELECT 
    CASE 
        WHEN "previous_purchases" > 5 THEN 'Repeat_Buyer (>5)'
        ELSE 'Regular_Buyer (<=5)'
    END AS buyer_type,
    "subscription_status",
    COUNT(*) AS customer_count,
    ROUND(100.0 * COUNT(*) / SUM(COUNT(*)) OVER (
        PARTITION BY CASE WHEN "previous_purchases" > 5 THEN 'Repeat_Buyer (>5)' ELSE 'Regular_Buyer (<=5)' END
    ), 2) AS percentage_share
FROM customer
GROUP BY buyer_type, "subscription_status"
ORDER BY buyer_type, customer_count DESC;


-- Q10. What is the revenue contribution of each age group?
SELECT 
    "age_group",
    SUM("purchase_amount") AS total_revenue,
    ROUND(100.0 * SUM("purchase_amount") / SUM(SUM("purchase_amount")) OVER (), 2) AS revenue_percentage
FROM customer
GROUP BY "age_group"
ORDER BY total_revenue DESC;